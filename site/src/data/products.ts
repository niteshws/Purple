/* ---------- Demonstration inventory (deterministic) ---------- */
function hash(s: string) {
  let h = 2166136261
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  return Math.abs(h)
}

/** Units in stock for a product / colour / size. Demo data, stable across reloads. */
export function stockFor(p: Product, color: string, size: string): number {
  const c = p.colors.find((x) => x.name === color)
  if (!c || c.soldOut) return 0
  if (p.sizeSystem === 'one-size') return 9
  const h = hash(`${p.handle}|${color}|${size}`)
  if (h % 9 === 0) return 0
  if (h % 6 === 0) return 2
  return 4 + (h % 12)
}
